import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const envPath=path.resolve(process.cwd(),'../.env');
const local=fs.existsSync(envPath)?Object.fromEntries(fs.readFileSync(envPath,'utf8').split('\n').filter(l=>l.includes('=')&&!l.startsWith('#')).map(l=>l.split(/=(.*)/s).slice(0,2))):{};
const apiBase=process.env.SETTLEGRAPH_API_URL??'http://127.0.0.1:8080';
const reviewerId='22222222-2222-4222-8222-222222222223';

test('real browser: assigned evidence, stale review and persisted same-key retry',async({page,request,context})=>{
  const login=await request.post(apiBase+'/v1/demo/sessions',{headers:{'X-Demo-Access-Code':process.env.DEMO_ACCESS_CODE??local.DEMO_ACCESS_CODE},data:{display_name:'Browser test owner'}});
  expect(login.status()).toBe(201);
  const session=await login.json();
  const headers={Authorization:'Bearer '+session.access_token,'X-Organization-Id':session.default_organization_id};
  const get=async(p:string)=>{const r=await request.get(apiBase+p,{headers});expect(r.ok()).toBeTruthy();return r.json();};
  await page.goto('/login');await page.getByLabel('Display name').fill('Browser Owner');
  await page.getByRole('button',{name:'Enter workspace'}).click();await expect(page).toHaveURL(/dashboard/);
  const cookies=await context.cookies();expect(cookies.find(c=>c.name==='sg_token')?.httpOnly).toBeTruthy();
  expect(cookies.find(c=>c.name==='sg_token')!.expires-Date.now()/1000).toBeLessThanOrEqual(3600);
  await page.goto('/simulation');
  const started=page.waitForResponse(r=>r.url().endsWith('/v1/demo/scenarios/delayed_settlement/runs')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Start selected scenario'}).click();
  const created=await started;expect(created.status()).toBe(201);const run=await created.json();
  for(let step=0;step<2;step++){
    const advanced=page.waitForResponse(r=>r.url().endsWith('/'+run.id+'/advance'));
    await page.getByRole('button',{name:'Advance step'}).click();expect((await advanced).status()).toBe(200);
  }
  let record!:{id:string;version:number};
  await expect.poll(async()=>{const cases=await get('/v1/cases?scenario_run_id='+run.id);record=cases.items[0];return Boolean(record);},{timeout:20000}).toBeTruthy();
  await page.goto('/cases?scenario_run_id='+run.id);
  await page.locator('a.case-list-item').first().click();
  await expect(page.getByRole('heading',{name:'Supporting evidence'})).toBeVisible();
  await page.getByLabel('Assignee',{exact:true}).selectOption(reviewerId);
  const assigned=page.waitForResponse(r=>r.url().endsWith('/'+record.id+'/assign'));
  await page.getByRole('button',{name:'Reassign Case'}).click();expect((await assigned).status()).toBe(200);
  expect((await get('/v1/cases/'+record.id)).assigned_to).toBe(reviewerId);
  await page.getByRole('button',{name:'Investigate evidence'}).click();
  await expect(page.locator('.ai-result').first()).toContainText('COMPLETED',{timeout:20000});
  await expect(page.locator('.ai-result').first()).toContainText('OFFLINE_STUB');
  await expect(page.locator('.ai-result a[href^="#evidence-"]').first()).toBeVisible();
  const etag=await context.request.get('/api/sg/v1/cases/'+record.id);expect(etag.headers()['etag']).toBeTruthy();
  await page.getByLabel('Decision',{exact:true}).selectOption('RESOLVE');
  await page.getByLabel('Reason (minimum 5 characters)').fill('Reviewed the cited synthetic evidence.');
  const advanced=await request.post(apiBase+'/v1/demo/scenario-runs/'+run.id+'/advance',{headers:{...headers,'Idempotency-Key':crypto.randomUUID()},data:{expected_step:2}});
  expect(advanced.status()).toBe(200);
  await expect.poll(async()=> (await get('/v1/cases/'+record.id)).status,{timeout:20000}).toBe('EVIDENCE_UPDATED');
  const stale=page.waitForResponse(r=>r.url().endsWith('/'+record.id+'/decisions'));
  await page.getByRole('button',{name:'Submit decision'}).click();expect((await stale).status()).toBe(412);
  await expect(page.getByRole('button',{name:'I reviewed the updated evidence'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Submit decision'})).toBeDisabled();
  await page.getByRole('button',{name:'I reviewed the updated evidence'}).click();
  let first=true;let throttle=true;const attempts:{key:string;body:string|null;match:string|undefined}[]=[];
  await page.route('**/api/sg/v1/cases/'+record.id+'/decisions',async route=>{
    const req=route.request();attempts.push({key:req.headers()['idempotency-key'],body:req.postData(),match:req.headers()['if-match']});
    if(first){first=false;const accepted=await route.fetch();expect(accepted.status()).toBe(200);await route.abort('failed');}
    else if(throttle){throttle=false;await route.fulfill({status:429,headers:{'Retry-After':'1'},json:{error:{code:'RATE_LIMITED',message:'Wait before retrying.',request_id:'rate-test'}}});}
    else await route.continue();
  });
  await page.getByRole('button',{name:'Submit decision'}).click();
  await expect(page.getByRole('button',{name:'Retry unconfirmed decision'})).toBeVisible();
  await page.reload();await expect(page.getByRole('button',{name:'Retry unconfirmed decision'})).toBeVisible();
  await expect(page.getByLabel('Reason (minimum 5 characters)')).toBeDisabled();
  await page.getByRole('button',{name:'Retry unconfirmed decision'}).click();
  await expect.poll(async()=>attempts.length).toBe(2);
  await expect(page.getByRole('button',{name:'Retry unconfirmed decision'})).toBeVisible();
  await page.getByRole('button',{name:'Retry unconfirmed decision'}).click();
  await expect.poll(async()=>attempts.length).toBe(3);expect(attempts[1]).toEqual(attempts[0]);expect(attempts[2]).toEqual(attempts[0]);
  await expect.poll(async()=> (await get('/v1/cases/'+record.id)).status).toBe('RESOLVED');
  const events=await get('/v1/cases/'+record.id+'/events');expect(events.items.filter((e:{type:string})=>e.type==='RESOLVED')).toHaveLength(1);
  await page.goto('/transactions?scenario_run_id='+run.id);
  const providers=(await get('/v1/providers')).items;
  const filtered=page.waitForResponse(r=>r.url().includes('/v1/transactions?')&&new URL(r.url()).searchParams.get('provider_id')===providers[0].id);
  await page.getByLabel('Filter provider').selectOption(providers[0].id);
  const payments=await filtered;expect(payments.status()).toBe(200);
  expect(new URL(payments.url()).searchParams.get('scenario_run_id')).toBe(run.id);
  expect((await payments.json()).items.every((t:{provider_id:string;scenario_run_id:string})=>t.provider_id===providers[0].id&&t.scenario_run_id===run.id)).toBeTruthy();
  await page.goto('/reconciliation');await expect(page.getByLabel('Evidence scope')).toHaveValue('SCENARIO_RUN');
  const queued=page.waitForResponse(r=>r.url().endsWith('/v1/reconciliation/runs')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Start reconciliation'}).click();
  const reconciliation=await queued;expect(reconciliation.status()).toBe(202);
  expect(reconciliation.request().postDataJSON()).toEqual({scope:'SCENARIO_RUN',scenario_run_id:run.id});
  const manual=await reconciliation.json();
  await expect.poll(async()=> (await get('/v1/reconciliation/runs/'+manual.id)).status,{timeout:20000}).toBe('COMPLETED');
  const chart=page.waitForResponse(r=>r.url().includes('/v1/dashboard/series?'));
  await page.goto('/dashboard');
  const points=(await (await chart).json()).points;
  const snapshot=await get('/v1/dashboard/summary');
  expect(points.at(-1).bucket_start.slice(0,10)).toBe(new Date(snapshot.latest_activity_at).toISOString().slice(0,10));
  expect(points.some((p:{payments_accepted:{minor_units:string}})=>BigInt(p.payments_accepted.minor_units)>0n)).toBeTruthy();
});

test('BFF actual routes enforce origin, route, body, role and expiry controls',async({page,request,context})=>{
  expect((await request.get('/api/sg/v1/providers')).status()).toBe(401);
  expect((await request.post('/api/sg/v1/demo/sessions',{data:{}})).status()).toBe(403);
  expect((await request.get('/api/sg/v1/not-a-public-operation')).status()).toBe(404);
  expect((await request.post('/api/session',{headers:{Origin:'https://untrusted.invalid'},data:{display_name:'Owner'}})).status()).toBe(403);
  await page.goto('/login');await page.getByRole('button',{name:'Enter workspace'}).click();await expect(page).toHaveURL(/dashboard/);
  expect((await page.request.post('/api/sg/v1/reconciliation/runs',{headers:{Origin:'https://untrusted.invalid'},data:{scope:'LATEST_OBSERVATIONS'}})).status()).toBe(403);
  expect((await page.request.post('/api/sg/v1/reconciliation/runs',{headers:{'Content-Type':'application/json'},data:' '.repeat(1048577)})).status()).toBe(413);
  await page.getByRole('button',{name:/sign out|log out/i}).click();await expect(page).toHaveURL(/login/);
  await page.getByLabel('Demo access code').fill(process.env.DEMO_VIEWER_ACCESS_CODE??local.DEMO_VIEWER_ACCESS_CODE);
  await page.getByRole('button',{name:'Enter workspace'}).click();await expect(page).toHaveURL(/dashboard/);
  await expect(page.getByRole('link',{name:'Bank simulator'})).toHaveCount(0);
  expect((await page.request.get('/api/sg/v1/members')).status()).toBe(403);
  expect((await page.request.post('/api/sg/v1/reconciliation/runs',{data:{scope:'LATEST_OBSERVATIONS'},headers:{'Idempotency-Key':crypto.randomUUID()}})).status()).toBe(403);
  const cookie=(await context.cookies()).find(c=>c.name==='sg_token')!;
  await context.addCookies([{...cookie,value:'expired-invalid-session'}]);
  expect((await page.request.get('/api/sg/v1/me')).status()).toBe(401);
  expect((await context.cookies()).some(c=>c.name==='sg_token'||c.name==='sg_org')).toBeFalsy();
  await page.goto('/dashboard');await expect(page).toHaveURL(/login/);
});
